"""Build INDEX.md: a sortable table of every entry's front matter.

Usage: python3 scripts/build_index.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP_DIRS = {"_templates", "scripts", "images", ".git"}
SKIP_FILES = {"README.md", "AGENTS.md", "CLAUDE.md", "INDEX.md"}


def read_front_matter(path):
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        return {}
    meta = {}
    for line in lines[1:]:
        if line.strip() == "---":
            break
        if ":" in line:
            key, value = line.split(":", 1)
            meta[key.strip()] = value.split("#", 1)[0].strip()
    return meta


def main():
    rows = []
    for path in sorted(ROOT.rglob("*.md")):
        rel = path.relative_to(ROOT)
        if rel.parts[0] in SKIP_DIRS or rel.name in SKIP_FILES:
            continue
        meta = read_front_matter(path)
        rows.append({
            "title": meta.get("title") or path.stem,
            "category": meta.get("category") or rel.parts[0],
            "tags": meta.get("tags", "").strip("[]"),
            "rating": meta.get("rating", ""),
            "added": meta.get("added", ""),
            "path": rel.as_posix(),
        })

    def rating(row):
        try:
            return -int(row["rating"])
        except ValueError:
            return 0

    rows.sort(key=lambda r: (r["category"], rating(r), r["title"].lower()))

    out = [
        "# Index",
        "",
        "Generated by `python3 scripts/build_index.py`. Don't edit by hand.",
        "",
        f"{len(rows)} entries, sorted by category, then rating (highest first).",
        "",
        "| Title | Category | Tags | Rating | Added |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        out.append(
            f"| [{r['title']}]({r['path']}) | {r['category']} | {r['tags']} | {r['rating']} | {r['added']} |"
        )
    (ROOT / "INDEX.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Wrote INDEX.md with {len(rows)} entries")


if __name__ == "__main__":
    main()
